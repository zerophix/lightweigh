# 防自指损坏：基字符必须存在（去掉 ?）。可选基字符会让正则退化为 [0-9#*]?，
# 一旦 strip 处理本文件删掉字面量 ⃣，该模式将删除任意文本的数字/#/*（历史事故）。
KEYCAP_RE = re.compile(r'[0-9#*]⃣')


def contains_emoji(text: str) -> bool:
    return bool(EMOJI_RE.search(text) or KEYCAP_RE.search(text))


def strip_emoji(text: str) -> str:
    text = KEYCAP_RE.sub("", text)
    text = EMOJI_RE.sub("", text)
    return text
